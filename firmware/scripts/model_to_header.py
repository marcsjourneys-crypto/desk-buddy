"""Turn the wake word model and its manifest into a C++ header the firmware compiles in.

    python scripts/model_to_header.py            (in firmware/; reads models/hey_carl.*)
    python scripts/model_to_header.py --ops      also list the model's operators

Reads models/hey_carl.tflite and models/hey_carl.json (ESPHome v2 manifest format) and
writes models/hey_carl_model.h: the manifest values as constants plus the model as a
16-byte-aligned const array. Run it by hand whenever the model or the manifest changes,
then rebuild. Without the header the firmware still builds, and `wake test` says there is
no model. Standard library only.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parent.parent
MODELS = FIRMWARE / "models"

# TFLite builtin operator codes (tensorflow/lite/schema/schema_generated.h) for the ops a
# microWakeWord streaming model may use; anything else prints as its number.
OP_NAMES = {
    0: "ADD",
    1: "AVERAGE_POOL_2D",
    2: "CONCATENATION",
    3: "CONV_2D",
    4: "DEPTHWISE_CONV_2D",
    6: "DEQUANTIZE",
    9: "FULLY_CONNECTED",
    14: "LOGISTIC",
    17: "MAX_POOL_2D",
    18: "MUL",
    22: "RESHAPE",
    34: "PAD",
    40: "MEAN",
    41: "SUB",
    45: "STRIDED_SLICE",
    49: "SPLIT",
    83: "PACK",
    102: "SPLIT_V",
    114: "QUANTIZE",
    129: "CALL_ONCE",
    142: "VAR_HANDLE",
    143: "READ_VARIABLE",
    144: "ASSIGN_VARIABLE",
}


class ModelError(Exception):
    pass


def check_manifest(manifest: dict) -> dict:
    """The fields the firmware uses, validated. Raises ModelError."""
    if manifest.get("type") != "micro" or manifest.get("version") != 2:
        raise ModelError('manifest: need "type": "micro" and "version": 2')
    micro = manifest.get("micro")
    if not isinstance(micro, dict):
        raise ModelError('manifest: missing the "micro" section')
    wake_word = manifest.get("wake_word")
    if not isinstance(wake_word, str) or not wake_word or '"' in wake_word or "\\" in wake_word:
        raise ModelError("manifest: wake_word must be a plain non-empty string")
    cutoff = micro.get("probability_cutoff")
    window = micro.get("sliding_window_size")
    step = micro.get("feature_step_size")
    arena = micro.get("tensor_arena_size")
    if not isinstance(cutoff, (int, float)) or not 0 < cutoff <= 1:
        raise ModelError("manifest: micro.probability_cutoff must be in (0, 1]")
    if not isinstance(window, int) or not 1 <= window <= 32:
        raise ModelError("manifest: micro.sliding_window_size must be 1-32")
    if step != 10:
        raise ModelError("manifest: micro.feature_step_size must be 10 (the frontend's step)")
    if not isinstance(arena, int) or not 1024 <= arena <= 1024 * 1024:
        raise ModelError("manifest: micro.tensor_arena_size must be 1024-1048576 bytes")
    return {"wake_word": wake_word, "cutoff": float(cutoff), "window": window, "arena": arena}


def check_model(data: bytes) -> None:
    if len(data) < 16 or data[4:8] != b"TFL3":
        raise ModelError("model: not a TFLite flatbuffer (no TFL3 identifier)")


def _u32(data: bytes, pos: int) -> int:
    return struct.unpack_from("<I", data, pos)[0]


def _field(data: bytes, table: int, index: int) -> int | None:
    """Absolute position of a flatbuffer table field, or None if it's absent."""
    vtable = table - struct.unpack_from("<i", data, table)[0]
    vtable_len = struct.unpack_from("<H", data, vtable)[0]
    slot = 4 + 2 * index
    if slot >= vtable_len:
        return None
    offset = struct.unpack_from("<H", data, vtable + slot)[0]
    return table + offset if offset else None


def operator_codes(data: bytes) -> list[int]:
    """The builtin operator codes in the model's operator_codes table (Model field 1)."""
    model = _u32(data, 0)
    pos = _field(data, model, 1)
    if pos is None:
        return []
    vector = pos + _u32(data, pos)
    codes = []
    for i in range(_u32(data, vector)):
        elem = vector + 4 + 4 * i
        table = elem + _u32(data, elem)
        dep = _field(data, table, 0)  # deprecated_builtin_code, int8
        new = _field(data, table, 3)  # builtin_code, int32
        dep_code = struct.unpack_from("<b", data, dep)[0] if dep is not None else 0
        new_code = struct.unpack_from("<i", data, new)[0] if new is not None else 0
        codes.append(max(dep_code, new_code))  # as TFLite's GetBuiltinCode() does
    return codes


def render(model: bytes, values: dict, source: str) -> str:
    digest = hashlib.sha256(model).hexdigest()
    lines = [
        "#pragma once",
        f"// Generated by scripts/model_to_header.py from {source} - do not edit.",
        f"// sha256 {digest}",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace wake_model {",
        "",
        f'constexpr char kWakeWord[] = "{values["wake_word"]}";',
        f"constexpr float kProbabilityCutoff = {values['cutoff']!r}f;",
        f"constexpr size_t kSlidingWindowSize = {values['window']};",
        "constexpr uint32_t kFeatureStepMs = 10;",
        f"constexpr size_t kTensorArenaSize = {values['arena']};",
        f"constexpr size_t kModelSize = {len(model)};",
        "",
        "alignas(16) const uint8_t kModel[] = {",
    ]
    for i in range(0, len(model), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in model[i : i + 16]) + ",")
    lines += ["};", "", "}  // namespace wake_model", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--name", default="hey_carl", help="model base name in models/")
    parser.add_argument("--ops", action="store_true", help="list the model's operators")
    args = parser.parse_args(argv)
    tflite = MODELS / f"{args.name}.tflite"
    manifest_path = MODELS / f"{args.name}.json"
    out = MODELS / f"{args.name}_model.h"
    try:
        model = tflite.read_bytes()
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        check_model(model)
        values = check_manifest(manifest)
    except FileNotFoundError as e:
        print(f"Missing {e.filename}", file=sys.stderr)
        return 1
    except (ModelError, json.JSONDecodeError) as e:
        print(e, file=sys.stderr)
        return 1
    if args.ops:
        try:
            codes = operator_codes(model)
        except struct.error:
            print("model: couldn't read its operator table", file=sys.stderr)
            return 1
        print("Operators:", ", ".join(OP_NAMES.get(c, f"op#{c}") for c in codes))
    out.write_text(render(model, values, tflite.name), encoding="utf-8", newline="\n")
    print(f"Wrote {out.relative_to(FIRMWARE)} ({len(model)} bytes of model)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
